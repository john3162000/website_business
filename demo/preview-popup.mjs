// Screenshots: the recipe pop-up (photo + credit, Paano lutuin card, no steps) and the share picture.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await ctx.addInitScript(() => { try { localStorage.setItem("sarapsulit.tour.v1", "done"); localStorage.setItem("sarapsulit.weatherMode", "sunny"); } catch {} });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("PAGE ERROR:", e.message));
const requests = [];
page.on("request", (r) => { if (/\/api\/recipes\/\d+$/.test(r.url())) requests.push(r.url()); });
await page.goto(process.argv[2], { waitUntil: "networkidle" });
await page.waitForFunction(() => typeof RECIPES !== "undefined" && RECIPES.length > 0, null, { timeout: 60000 });
const id = await page.evaluate(() => (RECIPES.find((r) => /^kare kare$/i.test(r.title)) || RECIPES.find((r) => /kare/i.test(r.title))).id);
await page.evaluate((i) => openModal(i), id);
await page.waitForTimeout(4000);
await page.screenshot({ path: "popup-out/1-popup-top.png" });
await page.evaluate(() => document.querySelector(".cook-card").scrollIntoView({ block: "center" }));
await page.waitForTimeout(800);
await page.screenshot({ path: "popup-out/2-paano-lutuin.png" });
console.log("steps shown:", await page.evaluate(() => /Instructions/.test(document.getElementById("modal-content").innerText)));
console.log("step fetches:", requests.length, "cook link:", await page.evaluate(() => document.querySelector(".cook-btn")?.href));
const png = await page.evaluate(async (i) => {
  const r = RECIPES.find((x) => x.id === i);
  const blob = await drawRecipeCard(r, MODAL_DATA.lines);
  return await new Promise((res) => { const fr = new FileReader(); fr.onload = () => res(fr.result); fr.readAsDataURL(blob); });
}, id);
writeFileSync("popup-out/3-share-picture.png", Buffer.from(png.split(",")[1], "base64"));
console.log("captured share picture");
const desk = await browser.newContext({ viewport: { width: 1366, height: 900 } });
await desk.addInitScript(() => { try { localStorage.setItem("sarapsulit.tour.v1", "done"); localStorage.setItem("sarapsulit.weatherMode", "sunny"); } catch {} });
const dp = await desk.newPage();
await dp.goto(process.argv[2], { waitUntil: "load" }).catch(() => {});
await dp.waitForTimeout(3000);
await dp.waitForFunction(() => typeof RECIPES !== "undefined" && RECIPES.length > 0, null, { timeout: 60000 });
await dp.evaluate((i) => openModal(i), id);
await dp.waitForTimeout(4000);
await dp.screenshot({ path: "popup-out/4-desktop.png" });
await browser.close();
