// Phone screenshots of the kitchen picker, the planner's save and grocery buttons, and the tour step.
import { createRequire } from "node:module";
import { join } from "node:path";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const OUT = "kitchen-out";
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, acceptDownloads: true });
await context.addInitScript(() => { try { localStorage.setItem("sarapsulit.tour.v1", "done"); localStorage.setItem("sarapsulit.weatherMode", "sunny"); } catch {} });
const page = await context.newPage();
page.on("pageerror", (e) => console.log("PAGE ERROR:", e.message));
const pause = (ms = 1200) => page.waitForTimeout(ms);
const shot = (n) => page.screenshot({ path: join(OUT, `${n}.png`) }).then(() => console.log("captured", n));
await page.goto(process.argv[2], { waitUntil: "networkidle" });
await page.waitForFunction(() => typeof RECIPES !== "undefined" && RECIPES.length > 0, null, { timeout: 60000 });
console.log("recipes with appliances:", await page.evaluate(() => RECIPES.filter((r) => r.appliances.length).length));
await page.evaluate(() => { showSection("browse"); document.querySelector(".kitchen-bar").scrollIntoView({ block: "center" }); });
await pause(); await shot("1-browse-bar");
await page.evaluate(() => openKitchen());
await pause(2500); await shot("2-kitchen-all");
await page.evaluate(() => { kitchenAll(false); toggleAppliance("air_fryer"); toggleAppliance("rice_cooker"); });
await pause(1500); await shot("3-kitchen-airfryer");
await page.evaluate(() => document.getElementById("kitchen-fact").scrollIntoView({ block: "center" }));
await pause(800); await shot("4-kitchen-fact");
console.log("count:", await page.evaluate(() => document.getElementById("kitchen-count").textContent));
await page.evaluate(() => applyKitchen());
await pause(1500);
await page.evaluate(() => document.querySelector(".kitchen-bar").scrollIntoView({ block: "start" }));
await pause(800); await shot("5-browse-filtered");
await page.evaluate(() => { const r = RECIPES.find((x) => x.appliances.includes("oven") && x.img) || RECIPES[0]; openModal(r.id); });
await page.waitForFunction(() => !/Loading/.test(document.getElementById("modal-content").textContent), null, { timeout: 30000 });
await pause(1000); await shot("6-modal-needs");
await page.evaluate(() => closeModal());
await page.evaluate(() => { showSection("planner"); document.getElementById("budget-text").value = "₱1,500 for the week, 4 people"; planOnBudget(); });
await pause(2500);
await page.evaluate(() => document.getElementById("plan-receipt").scrollIntoView({ block: "start" }));
await pause(1000); await shot("7-planner-receipt");
await page.evaluate(() => { window.prompt = () => "Linggo ng Oct 22"; saveNamedPlan(); });
await pause(800);
await page.evaluate(() => document.getElementById("plan-save-note").scrollIntoView({ block: "center" }));
await pause(800); await shot("8-planner-saved");
const text = await page.evaluate(() => currentGroceryText());
console.log("GROCERY:\n" + (text || "").split("\n").slice(0, 14).join("\n"));
const dl = page.waitForEvent("download", { timeout: 20000 }).catch(() => null);
await page.evaluate(() => downloadGroceryList());
const d = await dl; console.log("download:", d ? d.suggestedFilename() : "none");
await page.evaluate(() => { startTour(); tourNext(TOUR_STEPS.findIndex((s) => s.target === ".kitchen-bar")); });
await pause(2500); await shot("9-tour-step");
await browser.close();
