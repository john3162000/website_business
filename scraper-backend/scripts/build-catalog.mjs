// Bundles data/catalog/{aliases,canonicals}.tsv into a TypeScript module the
// API routes import, so serverless functions don't read files at runtime.
// Run after editing the catalog: node scripts/build-catalog.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const readTsv = (p) => {
  // \r?\n: a Windows checkout (core.autocrlf) has CRLF lines, and a stray \r would
  // rename the last column ("note\r") and drop every value in it.
  const [head, ...rows] = readFileSync(join(root, p), "utf8").split(/\r?\n/).filter((l) => l.trim());
  const cols = head.split("\t");
  return rows.map((r) => Object.fromEntries(r.split("\t").map((v, i) => [cols[i], v ?? ""])));
};
const num = (v) => (v === undefined || v === "" || isNaN(parseFloat(v)) ? null : parseFloat(v));

const aliases = {};
for (const a of readTsv("data/catalog/aliases.tsv")) {
  aliases[a.nameKey] = { lineClass: a.lineClass, slugs: a.slugs ? a.slugs.split("|") : [], size: a.size || null, note: a.note || null };
}

const canonicals = {};
for (const c of readTsv("data/catalog/canonicals.tsv")) {
  canonicals[c.slug] = {
    label: c.label, fnriCode: c.fnriCode || null, daName: c.daName || null, psaName: c.psaName || null, dietClass: c.dietClass || null,
    gPerCup: num(c.gPerCup), gEach: num(c.gEach), gEachSmall: num(c.gEachSmall), gEachLarge: num(c.gEachLarge),
    gClove: num(c.gClove), gHead: num(c.gHead), gThumb: num(c.gThumb), gBunch: num(c.gBunch),
    gStalk: num(c.gStalk), gSlice: num(c.gSlice), epPct: num(c.epPct), role: c.role || "normal",
    nutrScale: num(c.nutrScale), cookedPerRaw: num(c.cookedPerRaw), confidence: c.confidence || null,
  };
}

const extra = {};
for (const e of readTsv("data/catalog/nutrients-extra.tsv")) {
  extra[e.slug] = { calories: num(e.kcal), protein: num(e.protein), fat: num(e.fat), carbohydrates: num(e.carbs), sodium: num(e.sodium), source: e.source };
}

const manualPrices = {};
for (const m of readTsv("data/catalog/manual-prices.tsv")) {
  manualPrices[m.slug] = { price: num(m.price), packAmount: num(m.packAmount), packUnit: m.packUnit, source: m.source };
}

const out = `// GENERATED by scripts/build-catalog.mjs from data/catalog/*.tsv — do not edit by hand.
import type { Alias, Canonical } from "./types.ts";

export const ALIASES: Record<string, Alias> = ${JSON.stringify(aliases)};

export const CANONICALS: Record<string, Canonical> = ${JSON.stringify(canonicals)};

/** Reference prices for pantry items DA doesn't list (DTI SRP etc.): price per pack of packAmount g/ml. */
export const MANUAL_PRICES: Record<string, { price: number | null; packAmount: number | null; packUnit: string; source: string }> = ${JSON.stringify(manualPrices)};

/** Approximate per-100 g values for catalog items FNRI doesn't have (spices, broths, sauces). */
export const EXTRA_NUTRIENTS: Record<string, { calories: number | null; protein: number | null; fat: number | null; carbohydrates: number | null; sodium: number | null; source: string }> = ${JSON.stringify(extra)};
`;
writeFileSync(join(root, "src/lib/recipe-compile/catalog.generated.ts"), out);
console.log(`aliases ${Object.keys(aliases).length}, canonicals ${Object.keys(canonicals).length}`);
